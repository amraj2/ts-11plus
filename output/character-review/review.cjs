const { chromium } = require('/Users/amraj/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  const page = await browser.newPage({viewport: {width: 1200, height: 1000}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('sparkstumble-v1', JSON.stringify({sound: false})));
  await page.goto('http://127.0.0.1:5011/stumble');
  await page.waitForFunction(() => !document.getElementById('playBtn').disabled, {timeout: 120000});
  const artwork = await page.evaluate(() => JSON.parse(document.body.dataset.characterArtwork));
  if (Object.keys(artwork).length !== 50) throw Error('Incomplete artwork roster');
  await page.screenshot({path:'output/character-review/lobby.png', fullPage:true});
  await page.addStyleTag({content: '#characters{grid-template-columns:repeat(10,1fr);max-height:none;width:1100px}.character:disabled{opacity:1}.character-art{width:88px;height:88px}'});
  await page.locator('#characters').screenshot({path:'output/character-review/all-50.png'});
  await page.reload();
  await page.waitForFunction(() => !document.getElementById('playBtn').disabled);
  await page.locator('[data-character="bixby"]').click();
  await page.locator('#playBtn').click();
  await page.waitForFunction(() => !document.getElementById('game').hidden);
  await page.waitForTimeout(6000);
  await page.screenshot({path:'output/character-review/race.png'});
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:5011/stumble');
  await page.waitForFunction(() => !document.getElementById('playBtn').disabled);
  await page.screenshot({path:'output/character-review/mobile.png',fullPage:true});
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  const result = {characters: Object.keys(artwork).length, errors, mobileOverflow: overflow};
  fs.writeFileSync('output/character-review/browser-results.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  await browser.close();
  if (errors.length || overflow) process.exitCode=1;
})();
